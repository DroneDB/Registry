#!/usr/bin/env python3
"""THIRD_PARTY_LICENSES.md: the NuGet packages that Registry.Web ships, with their licence texts.

The list comes from the restore of Registry.Web (Registry.Web/obj/project.assets.json): every
package that puts files into a build, for any platform the release publishes (runtime and native assets,
native assets per runtime, satellite resources); packages that only compile or only carry build tasks
and analyzers, such as the SDK's trimming tasks, ship nothing. The licence of each package comes from its
.nuspec: an SPDX expression, a licence file inside the package, or (old packages) a licence URL that
LEGACY_LICENSE_URLS maps to an SPDX identifier. Standard licence texts come from the SPDX licence list.

    python3 scripts/third-party-licenses.py          # write THIRD_PARTY_LICENSES.md (needs network)
    python3 scripts/third-party-licenses.py --check  # fail when the packages or versions in the file
                                                     # differ from the restore (offline, for CI)

Run `dotnet restore Registry.Web` (or a build) first.
"""
import json
import pathlib
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "Registry.Web" / "obj" / "project.assets.json"
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
TARGET = "net10.0"
SHIPPED_ASSETS = ("runtime", "native", "runtimeTargets", "resource")
SPDX_TEXT = "https://raw.githubusercontent.com/spdx/license-list-data/main/text/{}.txt"

# Packages published before NuGet had license expressions name a URL only.
LEGACY_LICENSE_URLS = {
    "http://www.apache.org/licenses/LICENSE-2.0": "Apache-2.0",
    "https://www.apache.org/licenses/LICENSE-2.0": "Apache-2.0",
    "http://www.apache.org/licenses/LICENSE-2.0.txt": "Apache-2.0",
    "https://github.com/StackExchange/Dapper/blob/master/License.txt": "Apache-2.0",
    "https://github.com/dotnet/corefx/blob/master/LICENSE.TXT": "MIT",
    "http://go.microsoft.com/fwlink/?LinkId=329770": "MS-NET-LIBRARY",
    "https://licenses.nuget.org/MIT": "MIT",
    "https://github.com/arnoldasgudas/Hangfire.MySqlStorage/blob/master/License.md": "LGPL-3.0-only",
    "https://raw.githubusercontent.com/pieceofsummer/Hangfire.Console/master/LICENSE.md": "MIT",
    "https://opensource.org/licenses/MIT": "MIT",
    "http://opensource.org/licenses/MIT": "MIT",
}
ROW = re.compile(r"^\| ([^|]+) \| ([^|]+) \| [^|]* \|", re.M)


def ships(target):
    """Whether a package puts files into a build ("_._" marks a folder that is empty on purpose)."""
    return any(not path.endswith("_._") for kind in SHIPPED_ASSETS for path in target.get(kind, {}))


def packages():
    assets = json.loads(ASSETS.read_text(encoding="utf-8"))
    folder = pathlib.Path(next(iter(assets["packageFolders"])))
    for key, value in sorted(assets["targets"][TARGET].items(), key=lambda kv: kv[0].lower()):
        if value.get("type") != "package" or not ships(value):
            continue
        name, version = key.split("/", 1)
        yield name, version, folder / assets["libraries"][key]["path"]


def nuspec(path, name):
    spec = next(path.glob("*.nuspec"))
    meta = ET.parse(spec).getroot().find("{*}metadata")
    get = lambda tag: (meta.findtext("{*}" + tag) or "").strip()
    licence = meta.find("{*}license")
    info = {"copyright": get("copyright"), "url": get("projectUrl"), "authors": get("authors")}
    if licence is not None and licence.get("type") == "expression":
        info["licence"] = licence.text.strip()
    elif licence is not None and licence.get("type") == "file":
        info["licence"] = "see the file of the package"
        info["file"] = path / licence.text.strip()
    else:
        url = get("licenseUrl")
        info["licence"] = LEGACY_LICENSE_URLS.get(url) or sys.exit(
            f"{name}: licence URL {url!r} is not in LEGACY_LICENSE_URLS; add the SPDX identifier it names")
    return info


def spdx_ids(expression):
    return [t for t in re.split(r"[\s()]+", expression) if t and t not in ("AND", "OR", "WITH")]


def spdx_text(identifier, cache={}):
    if identifier not in cache:
        with urllib.request.urlopen(SPDX_TEXT.format(identifier), timeout=30) as response:
            cache[identifier] = response.read().decode("utf-8").strip()
    return cache[identifier]


def render(rows):
    lines = [
        "# Third-party licences",
        "",
        "The NuGet packages that Registry ships, with their licences. They are not covered by the DroneDB",
        "Source-Available License (see [NOTICE.md](NOTICE.md)). The .NET runtime that the self-contained",
        "build includes is MIT-licensed by the .NET Foundation; its own notices ship with the runtime.",
        "",
        "Generated by `scripts/third-party-licenses.py` from the restore of Registry.Web; do not edit by hand.",
        "",
        "| Package | Version | Licence |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {n} | {v} | {i['licence']} |" for n, v, i in rows]
    for n, v, i in rows:
        if "file" in i:
            lines += ["", f"## {n} {v}", "", "```text", i["file"].read_text(encoding="utf-8", errors="replace").strip(), "```"]
    by_id = {}
    for n, v, i in rows:
        for identifier in spdx_ids(i["licence"]) if "file" not in i else []:
            by_id.setdefault(identifier, []).append((n, i["copyright"]))
    for identifier in sorted(by_id):
        lines += ["", f"## {identifier}", "", "Packages: " + ", ".join(sorted({n for n, _ in by_id[identifier]})) + ".", ""]
        notices = sorted({c for _, c in by_id[identifier] if c})
        lines += [f"- {c}" for c in notices]
        if identifier == "MS-NET-LIBRARY":
            lines += ["", "The Microsoft .NET Library License: <http://go.microsoft.com/fwlink/?LinkId=329770>."]
        else:
            lines += ["", "```text", spdx_text(identifier), "```"]
    return "\n".join(lines) + "\n"


def main():
    rows = [(n, v, nuspec(p, n)) for n, v, p in packages()]
    if "--check" in sys.argv:
        expected = {(n, v) for n, v, _ in rows}
        written = {(a.strip(), b.strip()) for a, b in ROW.findall(OUTPUT.read_text(encoding="utf-8"))} - {("Package", "Version"), ("---", "---")}
        if expected != written:
            for n, v in sorted(expected - written):
                print(f"missing from {OUTPUT.name}: {n} {v}")
            for n, v in sorted(written - expected):
                print(f"no longer shipped: {n} {v}")
            sys.exit(f"{OUTPUT.name} is out of date: run python3 scripts/third-party-licenses.py")
        print(f"{OUTPUT.name}: {len(rows)} packages, up to date")
        return
    OUTPUT.write_text(render(rows), encoding="utf-8")
    print(f"wrote {OUTPUT.name}: {len(rows)} packages")


if __name__ == "__main__":
    main()
